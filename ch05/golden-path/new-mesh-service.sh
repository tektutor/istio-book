#!/usr/bin/env bash
# The golden path for one service: print the mesh resources that every
# service in TekTutor Shop needs, with the platform team's defaults.
#
#   usage: new-mesh-service.sh NAMESPACE SERVICE PORT CALLER [CALLER...]
#   example: new-mesh-service.sh shop inventory 8080 orders reports
#
# Each CALLER is a service account in the same namespace. Review the
# output, commit it to Git and let the pipeline apply it.
set -euo pipefail

if [ "$#" -lt 4 ]; then
  sed -n '5,6p' "$0" >&2                  # print the usage lines
  exit 2
fi

NS="$1" SVC="$2" PORT="$3"
shift 3
TIMEOUT="${TIMEOUT:-5s}"                  # (1)
TRUST_DOMAIN="${TRUST_DOMAIN:-cluster.local}"
MODE="${MODE:-sidecar}"                   # (2)

# Who enforces the access policy. In ambient mode, the route needs a
# waypoint, so the waypoint must check the caller's identity.
if [ "$MODE" = ambient ]; then
  TARGET="  targetRefs:
  - kind: Service
    group: \"\"
    name: $SVC"
else
  TARGET="  selector:
    matchLabels:
      app: $SVC"
fi

cat <<YAML                                # (3)
# Generated by new-mesh-service.sh for $NS/$SVC. Edit with care.
apiVersion: gateway.networking.k8s.io/v1
kind: HTTPRoute
metadata:
  name: $SVC
  namespace: $NS
  labels:
    mesh.tektutor.org/generated-by: golden-path
spec:
  parentRefs:
  - group: ""
    kind: Service
    name: $SVC
    port: $PORT
  rules:
  - backendRefs:
    - name: $SVC
      port: $PORT
    timeouts:
      request: $TIMEOUT
---
apiVersion: security.istio.io/v1
kind: AuthorizationPolicy
metadata:
  name: $SVC-allow-callers
  namespace: $NS
  labels:
    mesh.tektutor.org/generated-by: golden-path
spec:
$TARGET
  action: ALLOW
  rules:
  - from:
    - source:
        principals:
YAML
for caller in "$@"; do                    # (4)
  echo "        - $TRUST_DOMAIN/ns/$NS/sa/$caller"
done
